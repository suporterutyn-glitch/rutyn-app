// Cada archivo de src/i18n/ es un namespace con sus tres idiomas.
const modulos = import.meta.glob<{ default: { pt: object; es: object; en: object } }>('../i18n/*.ts', { eager: true })
const resources: Record<'pt' | 'es' | 'en', Record<string, object>> = { pt: { ...pt }, es: { ...es }, en: { ...en } }
for (const [ruta, mod] of Object.entries(modulos)) {
  if (!mod.default) continue
  const ns = ruta.split('/').pop()!.replace(/\.ts$/, '')
  resources.pt[ns] = mod.default.pt
  resources.es[ns] = mod.default.es
  resources.en[ns] = mod.default.en
}

void i18n.use(initReactI18next).init({
  resources: resources as any,
  lng: initialLang(),
  fallbackLng: 'pt',
  defaultNS: 'common',
  ns: Object.keys(resources.pt),
  interpolation: { escapeValue: false },
})

export async function setLang(lang: 'pt' | 'es' | 'en') {
  localStorage.setItem(STORAGE_KEY, lang)
  try {
    await i18n.changeLanguage(lang)
  } catch (err) {
    console.error('Failed to change language to', lang, err)
  }
  void guardarIdiomaEnCuenta(lang)
}

/**
 * Con sesión abierta, el idioma elegido queda también en la cuenta: los
 * correos de Supabase (supabase/correos) salen en user_metadata.language.
 */
async function guardarIdiomaEnCuenta(lang: 'pt' | 'es' | 'en') {
  const { supabase } = await import('./supabase')
  const { data } = await supabase.auth.getSession()
  const user = data.session?.user
  if (!user || user.user_metadata?.language === lang) return
  await Promise.all([
    supabase.auth.updateUser({ data: { language: lang } }),
    supabase.from('profiles').update({ language: lang }).eq('id', user.id),
  ])
}

export default i18n
